// Current language
let currentLanguage = localStorage.getItem("language") || "tr";

// Initialize language on page load
function initLanguage() {
    setLanguage(currentLanguage);
}

// Set language function
function setLanguage(lang) {
    if (!translations[lang]) return;

    currentLanguage = lang;
    localStorage.setItem("language", lang);

    // Update HTML lang attribute
    document.documentElement.lang = lang;

    // Update all elements with data-i18n attribute
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        if (translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // Update language toggle button
    const languageBtn = document.getElementById("languageToggle");
    if (languageBtn) {
        languageBtn.textContent = lang === "tr" ? "EN" : "TR";
    }

    // Update page title based on language
    if (lang === "tr") {
        document.title = "Thomas Barber | Modern Erkek Bakım Salonu";
    } else {
        document.title = "Thomas Barber | Modern Men's Grooming Salon";
    }
}

// Language toggle button handler
document.addEventListener("DOMContentLoaded", () => {
    initLanguage();

    const languageBtn = document.getElementById("languageToggle");
    if (languageBtn) {
        languageBtn.addEventListener("click", () => {
            const newLang = currentLanguage === "tr" ? "en" : "tr";
            setLanguage(newLang);
        });
    }

    // Smooth scroll for navigation links
    document.querySelectorAll("a[href^='#']").forEach((link) => {
        link.addEventListener("click", (e) => {
            const href = link.getAttribute("href");
            if (href === "#") return;

            const target = document.querySelector(href);
            if (target) {
                e.preventDefault();
                target.scrollIntoView({ behavior: "smooth" });
            }
        });
    });
});
